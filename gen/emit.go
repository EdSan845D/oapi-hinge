// 发射器：IR → 生成文件。
//   - <out>/specs_gen.go        端点描述变量（hinge.Endpoint）
//   - <out>/binders_gen.go      类型化绑定器（按 Q/B 类型去重；请求期零反射）
//   - <out>/register_<t>_gen.go 各框架注册函数（gin/echo/http）+ RegisterAll
//   - <pkgDir>/hinge_gen_table.go  Enterpoint 守卫 + Endpoints() 对应关系表

// Run 生成入口：解析 → IR → 发射（写盘；check=true 时只校验产物是否最新）。
func Run(rootDir string, cfg Config, check bool) error {
	fset := token.NewFileSet()
	pkgs, err := collectDirs(fset, rootDir, cfg.Module, cfg.Scan)
	if err != nil {
		return err
	}
	eps, err := buildIR(pkgs)
	if err != nil {
		return err
	}
	files, err := Emit(cfg, eps)
	if err != nil {
		return err
	}
	if check {
		var stale []string
		for rel, content := range files {
			full := filepath.Join(rootDir, filepath.FromSlash(rel))
			old, rerr := os.ReadFile(full)
			if rerr != nil {
				stale = append(stale, rel+"（缺失，运行 hinge gen 生成）")
				continue
			}
			if string(old) != content {
				stale = append(stale, rel+"（内容过期，运行 hinge gen 重新生成）")
			}
		}
		if len(stale) > 0 {
			return fmt.Errorf("生成产物过期：\n  - %s", strings.Join(stale, "\n  - "))
		}
		fmt.Fprintf(os.Stderr, "hinge check: %d 个生成文件全部最新（%d 个端点）\n", len(files), len(eps))
		return nil
	}
	for rel, content := range files {
		full := filepath.Join(rootDir, filepath.FromSlash(rel))
		if err := os.MkdirAll(filepath.Dir(full), 0o755); err != nil {
			return err
		}
		if err := os.WriteFile(full, []byte(content), 0o644); err != nil {
			return err
		}
	}
	owners := map[string]bool{}
	for _, ep := range eps {
		owners[ep.Pkg.ImportPath+"/"+ep.Owner] = true
	}
	fmt.Fprintf(os.Stderr, "hinge gen: %d 端点 / %d Enterpoint / %d 个生成文件\n", len(eps), len(owners), len(files))
	return nil
}

// genHeader 生成文件头。
func genHeader(cfg Config) string {
	return "// Code generated by hinge gen. DO NOT EDIT.\n" +
		"// 源：oapi:* 注解端点（scan=" + strings.Join(cfg.Scan, ",") + "）\n" +
		"// 重新生成：go run github.com/EdSan845D/oapi-hinge/cmd/hinge gen\n\n"
}

// pkgAlias 包导入别名登记：同名包自动加后缀，保证生成文件内不冲突。
func pkgAlias(is *importSet, taken map[string]string, pkgPath, want string) string {
	if prev, ok := taken[pkgPath]; ok {
		return prev
	}
	alias := want
	for n := 2; ; n++ {
		used := false
		for _, a := range taken {
			if a == alias {
				used = true
				break
			}
		}
		if !used {
			break
		}
		alias = fmt.Sprintf("%s%d", want, n)
	}
	taken[pkgPath] = alias
	is.add(pkgPath, alias)
	return alias
}

// Emit 生成全部文件内容（相对模块根路径 → 内容）。
func Emit(cfg Config, eps []*EndpointIR) (map[string]string, error) {
	files := map[string]string{}

	specs, err := emitSpecs(cfg, eps)
	if err != nil {
		return nil, err
	}
	files[cfg.Out+"/specs_gen.go"] = specs

	binders, err := emitBinders(cfg, eps)
	if err != nil {
		return nil, err
	}
	files[cfg.Out+"/binders_gen.go"] = binders

	for _, target := range cfg.Targets {
		reg, err := emitRegister(cfg, eps, target)
		if err != nil {
			return nil, err
		}
		files[fmt.Sprintf("%s/register_%s_gen.go", cfg.Out, target)] = reg
	}
	all, err := emitAll(cfg, eps)
	if err != nil {
		return nil, err
	}
	files[cfg.Out+"/all_gen.go"] = all

	// 表文件：每个扫描包一个（包含该包全部 Enterpoint）
	byPkg := map[*Package][]*EndpointIR{}
	for _, ep := range eps {
		byPkg[ep.Pkg] = append(byPkg[ep.Pkg], ep)
	}
	pkgList := make([]*Package, 0, len(byPkg))
	for p := range byPkg {
		pkgList = append(pkgList, p)
	}
	sort.Slice(pkgList, func(i, j int) bool { return pkgList[i].Dir < pkgList[j].Dir })
	for _, pkg := range pkgList {
		tbl, err := emitTable(pkg, byPkg[pkg])
		if err != nil {
			return nil, err
		}
		files[pkg.Dir+"/hinge_gen_table.go"] = tbl
	}
	return files, nil
}

// emitSpecs 端点描述变量（注册函数与表共用同一套事实的 apigen 侧副本）。
func emitSpecs(cfg Config, eps []*EndpointIR) (string, error) {
	is := newImportSet()
	is.add(hingeImportPath, "")
	taken := map[string]string{} // owner 包别名表（预登记，渲染器引用同名）
	for _, ep := range eps {
		pkgAlias(is, taken, ep.Pkg.ImportPath, ep.Pkg.Name)
	}
	// 两遍组装：先渲染端点块（渲染会向 is 补充 import），最后统一落头部
	var body strings.Builder
	for _, ep := range eps {
		ownerAlias := taken[ep.Pkg.ImportPath]
		body.WriteString(fmt.Sprintf("var spec%s%s = hinge.Endpoint{\n", ep.Owner, ep.Handler))
		fmt.Fprintf(&body, "\tOwner:   %q,\n", ep.Owner)
		fmt.Fprintf(&body, "\tHandler: %q,\n", ep.Handler)
		fmt.Fprintf(&body, "\tMethod:  %q,\n", ep.Method)
		fmt.Fprintf(&body, "\tPath:    %q,\n", ep.FullPath)
		fmt.Fprintf(&body, "\tSummary: %q,\n", ep.Summary)
		if ep.Description != "" {
			fmt.Fprintf(&body, "\tDescription: %q,\n", ep.Description)
		}
		if len(ep.Tags) > 0 {
			fmt.Fprintf(&body, "\tTags: []string{%s},\n", quoteList(ep.Tags))
		}
		if ep.Status != 0 {
			fmt.Fprintf(&body, "\tStatus: %d,\n", ep.Status)
		}
		if ep.Deprecated {
			body.WriteString("\tDeprecated: true,\n")
		}
		if ep.Envelope != "" {
			fmt.Fprintf(&body, "\tEnvelope: %q,\n", ep.Envelope)
		}
		if ep.Auth != "" {
			fmt.Fprintf(&body, "\tAuth: %q,\n", ep.Auth)
		}
		if ep.Limit != "" {
			fmt.Fprintf(&body, "\tLimit: %q,\n", ep.Limit)
		}
		if ep.TimeoutStr != "" {
			fmt.Fprintf(&body, "\tTimeout: hinge.MustDuration(%q),\n", ep.TimeoutStr)
		}
		if len(ep.Middleware) > 0 {
			fmt.Fprintf(&body, "\tMiddleware: []string{%s},\n", quoteList(ep.Middleware))
		}
		if ep.HasQ {
			fmt.Fprintf(&body, "\tQType: hinge.Type[%s.%s](),\n", ownerAlias, ep.QName)
		}
		if ep.HasB {
			bType := ownerAlias + "." + ep.BName
			if ep.BodyKind == "raw" {
				bType = "hinge.RawBody"
			}
			fmt.Fprintf(&body, "\tBType: hinge.Type[%s](),\n", bType)
		}
		rd := &renderer{pkg: ep.Pkg, ownerAlias: ownerAlias, src: ep.RSrcFile, is: is}
		rExpr, err := rd.expr(ep.RExpr)
		if err != nil {
			return "", fmt.Errorf("%s.%s R 类型: %w", ep.Owner, ep.Handler, err)
		}
		fmt.Fprintf(&body, "\tRType: hinge.Type[%s](),\n", rExpr)
		body.WriteString("}\n\n")
	}

	var b strings.Builder
	b.WriteString(genHeader(cfg))
	b.WriteString("package " + cfg.Pkg + "\n\n")
	b.WriteString(is.block())
	b.WriteString("\n")
	b.WriteString(body.String())
	return b.String(), nil
}

// binderPlan 绑定器发射计划（按 类型+角色 去重）。
type binderPlan struct {
	key   string // role|pkgPath|typeName
	role  string // "Q" / "B"
	ep    *EndpointIR
	name  string
}

func emitBinders(cfg Config, eps []*EndpointIR) (string, error) {
	is := newImportSet()
	is.add("context", "")
	is.add(hingeImportPath, "")
	taken := map[string]string{}
	plans := make([]*binderPlan, 0, len(eps)*2)
	byName := map[string]*binderPlan{}

	// 去重注册：Q 按类型；B 按 类型+bodyKind（json/multipart 同类型不同 binder，key 含 kind）
	reg := func(role, kind string, ep *EndpointIR, typeName string) *binderPlan {
		key := role + "|" + kind + "|" + ep.Pkg.ImportPath + "|" + typeName
		if p, ok := byName[key]; ok {
			return p
		}
		base := "bind" + role + typeName
		name := base
		for n := 2; ; n++ {
			if _, dup := byName[name]; !dup {
				break
			}
			name = fmt.Sprintf("%s_%d", base, n)
		}
		p := &binderPlan{key: key, role: role, ep: ep, name: name}
		byName[key] = p
		byName[name] = p
		plans = append(plans, p)
		return p
	}
	for _, ep := range eps {
		pkgAlias(is, taken, ep.Pkg.ImportPath, ep.Pkg.Name)
		if ep.HasQ {
			ep.qBinder = reg("Q", "", ep, ep.QName).name
		}
		if ep.HasB {
			ep.bBinder = reg("B", ep.BodyKind, ep, ep.BName).name
		}
	}
	// fmt 仅在有 Validate() 直调的绑定器中需要（validate failed: %w 包装）
	hasFmt := false
	for _, p := range plans {
		if (p.role == "Q" && p.ep.ValidateQ) || (p.role == "B" && p.ep.ValidateB) {
			hasFmt = true
			break
		}
	}
	if hasFmt {
		is.add("fmt", "")
	}
	// bindRawBody 共享（raw 形态单一实现）
	hasRaw := false
	for _, ep := range eps {
		if ep.HasB && ep.BodyKind == "raw" {
			hasRaw = true
		}
	}

	var bodies strings.Builder

	if hasRaw {
		bodies.WriteString(`// bindRawBody 原始字节体绑定：整包透传（webhook 验签 / 自定义编码）。
func bindRawBody(ctx context.Context, r hinge.RequestReader) (any, error) {
	data, err := r.Body()
	if err != nil {
		return nil, err
	}
	if data == nil {
		data = []byte{}
	}
	return hinge.RawBody(data), nil
}

`)
	}

	sort.Slice(plans, func(i, j int) bool { return plans[i].name < plans[j].name })
	for _, p := range plans {
		var body strings.Builder
		var err error
		if p.role == "Q" {
			err = emitQBinder(&body, p.ep, is, taken)
		} else {
			err = emitBBinder(&body, p.ep, is, taken)
		}
		if err != nil {
			return "", err
		}
		sig := fmt.Sprintf("func %s(ctx context.Context, r hinge.RequestReader) (any, error) {\n", p.name)
		bodies.WriteString(sig)
		bodies.WriteString(body.String())
		bodies.WriteString("}\n\n")
	}

	var b strings.Builder
	b.WriteString(genHeader(cfg))
	b.WriteString("package " + cfg.Pkg + "\n\n")
	b.WriteString(is.block())
	b.WriteString("\n")
	b.WriteString(bodies.String())
	return b.String(), nil
}

// emitFieldBlock 发射单字段绑定块（按来源分派；语义对齐 v0.1 bindFields/setValue）。
// 每个字段用自己的源文件上下文渲染类型（内嵌字段可能来自同包其他文件）。
func emitFieldBlock(b *strings.Builder, f Field, pkg *Package, ownerAlias string, is *importSet, immediate bool) error {
	rd := &renderer{pkg: pkg, ownerAlias: ownerAlias, src: f.SrcFile, is: is}
	t, err := rd.expr(f.TypeExpr)
	if err != nil {
		return fmt.Errorf("字段 %s: %w", f.GoName, err)
	}
	in := f.In
	if in == "" {
		in = "query" // Q 的 form 标签语义与 query 相同（v0.1 setValue(c, f, name, false)）
	}
	valExpr := "raw"
	if in == "query" || in == "form" {
		valExpr = "vals[0]"
	}
	if in == "path" {
		fmt.Fprintf(b, "\tif raw, ok := r.PathParam(%q); ok {\n", f.Source)
	} else if in == "header" {
		fmt.Fprintf(b, "\tif raw, ok := r.Header(%q); ok {\n", f.Source)
	} else if in == "cookie" {
		fmt.Fprintf(b, "\tif raw, ok := r.Cookie(%q); ok {\n", f.Source)
	} else { // query / form（B 的 form 走独立分支，不走这里）
		fmt.Fprintf(b, "\tif vals, ok := r.QueryValues(%q); ok && len(vals) > 0 && vals[0] != \"\" {\n", f.Source)
	}
	if f.Class == classSlice && (in == "query" || in == "form") {
		src := "hinge.Flat(vals)"
		if f.BaseKind == "string" {
			src = "vals" // v0.1：[]string 不拆逗号（SetSliceValue 首分支）
		}
		fmt.Fprintf(b, "\t\txs, err := hinge.ParseSlice[%s](%s, %q)\n", t, src, f.Source)
	} else if f.Class == classSlice {
		// v0.1 语义：path/header/cookie 切片经 SetRaw→SetSliceValue([]string{raw})，单元素切片
		fmt.Fprintf(b, "\t\txs, err := hinge.ParseSlice[%s]([]string{raw}, %q)\n", t, f.Source)
	} else {
		switch f.Class {
		case classScalar, classPtrScalar:
			fmt.Fprintf(b, "\t\tx, err := hinge.Parse[%s](%s, %q)\n", t, valExpr, f.Source)
		default:
			return fmt.Errorf("字段 %s：来源 %s 不支持该类型形态", f.GoName, in)
		}
	}
	if immediate {
		b.WriteString("\t\tif err != nil {\n\t\t\treturn v, err\n\t\t}\n")
	} else {
		fmt.Fprintf(b, "\t\tif err != nil {\n\t\t\tadd(%q, %q, err.Error())\n\t\t} else {\n", f.Source, in)
	}
	switch f.Class {
	case classScalar:
		b.WriteString("\t\t" + f.Access + " = x\n")
	case classPtrScalar:
		b.WriteString("\t\t" + f.Access + " = &x\n")
	case classSlice:
		b.WriteString("\t\t" + f.Access + " = xs\n")
	}
	if immediate {
		b.WriteString("\t}\n")
	} else {
		b.WriteString("\t\t}\n\t}\n")
	}
	// default 标签：仅 query/form/cookie（对齐 v0.1：path/header 无 default 分支）
	if f.Def != "" && (in == "query" || in == "cookie" || in == "form") {
		fmt.Fprintf(b, "\tif %s {\n", zeroCmp(f))
		switch f.Class {
		case classSlice:
			fmt.Fprintf(b, "\t\txs, err := hinge.ParseSlice[%s](%s, %q)\n", t, sliceDefSrc(f), f.Source)
		default:
			fmt.Fprintf(b, "\t\tx, err := hinge.Parse[%s](%s, %q)\n", t, strconv.Quote(f.Def), f.Source)
		}
		if immediate {
			b.WriteString("\t\tif err != nil {\n\t\t\treturn v, err\n\t\t}\n")
		} else {
			fmt.Fprintf(b, "\t\tif err != nil {\n\t\t\tadd(%q, %q, err.Error())\n\t\t} else {\n", f.Source, in)
		}
		switch f.Class {
		case classScalar:
			b.WriteString("\t\t" + f.Access + " = x\n")
		case classPtrScalar:
			b.WriteString("\t\t" + f.Access + " = &x\n")
		case classSlice:
			b.WriteString("\t\t" + f.Access + " = xs\n")
		}
		if immediate {
			b.WriteString("\t}\n")
		} else {
			b.WriteString("\t\t}\n\t}\n")
		}
	}
	return nil
}

// zeroCmp 字段零值判断表达式（对齐 v0.1 reflect IsZero 语义）。
func zeroCmp(f Field) string {
	switch f.Class {
	case classScalar:
		switch f.BaseKind {
		case "string":
			return f.Access + ` == ""`
		case "bool":
			return "!" + f.Access
		case "time.Time":
			return f.Access + ".IsZero()"
		default:
			return f.Access + " == 0"
		}
	case classPtrScalar, classFile:
		return f.Access + " == nil"
	default:
		return "len(" + f.Access + ") == 0"
	}
}

// emitRequiredChecks 必填检查（对齐 v0.1 checkRequired：绑定/default 之后判断）。
func emitRequiredChecks(b *strings.Builder, fs *fieldSet) {
	for _, f := range fs.Fields {
		if !f.Required {
			continue
		}
		in := f.In
		if in == "" {
			in = "body"
		}
		fmt.Fprintf(b, "\tif %s {\n\t\tadd(%q, %q, \"is required\")\n\t}\n", zeroCmp(f), f.Source, in)
	}
}

// emitInTransform InTransform 生成期直调（零反射）。
func emitInTransform(b *strings.Builder, has, ptr bool) {
	if has {
		recv := "v"
		if ptr {
			recv = "(&v)"
		}
		fmt.Fprintf(b, "\tif err := %s.InTransform(ctx); err != nil {\n\t\treturn v, err\n\t}\n", recv)
	}
}

// emitValidate Validate 生成期直调（零反射）。
func emitValidate(b *strings.Builder, has, ptr bool) {
	if has {
		recv := "v"
		if ptr {
			recv = "(&v)"
		}
		fmt.Fprintf(b, "\tif err := %s.Validate(); err != nil {\n\t\treturn v, fmt.Errorf(\"validate failed: %%w\", err)\n\t}\n", recv)
	}
}

// emitQBinder query/path/header/cookie 绑定器（逐字段收集，不快速失败）。
func emitQBinder(b *strings.Builder, ep *EndpointIR, is *importSet, taken map[string]string) error {
	ownerAlias := taken[ep.Pkg.ImportPath]
	fmt.Fprintf(b, "\tvar v %s.%s\n", ownerAlias, ep.QName)
	fmt.Fprintf(b, "\tbe := &hinge.BindError{}\n\tadd := be.AddField\n")
	if len(ep.QSet.Fields) == 0 && len(requiredFields(ep.QSet)) == 0 {
		b.WriteString("\t_ = add\n")
	}
	// 指针内嵌分配
	for _, a := range ep.QSet.Allocs {
		rd2 := &renderer{pkg: ep.Pkg, ownerAlias: ownerAlias, src: a.SrcFile, is: is}
		t, err := rd2.expr(ast.NewIdent(a.TypeName))
		if err != nil {
			return err
		}
		fmt.Fprintf(b, "\tif %s == nil {\n\t\t%s = new(%s)\n\t}\n", a.Access, a.Access, t)
	}
	for _, f := range ep.QSet.Fields {
		if err := emitFieldBlock(b, f, ep.Pkg, ownerAlias, is, false); err != nil {
			return err
		}
	}
	b.WriteString("\tif len(be.Fields) > 0 {\n\t\treturn v, be\n\t}\n")
	emitInTransform(b, ep.InTransformQ, ep.InTransformQPtr)
	emitRequiredChecks(b, ep.QSet)
	b.WriteString("\tif len(be.Fields) > 0 {\n\t\treturn v, be\n\t}\n")
	emitValidate(b, ep.ValidateQ, ep.ValidateQPtr)
	b.WriteString("\tif len(be.Fields) > 0 {\n\t\treturn v, be\n\t}\n\treturn v, nil\n")
	return nil
}

// emitBBinder body 绑定器（json / multipart；raw 由共享 bindRawBody 承担）。
func emitBBinder(b *strings.Builder, ep *EndpointIR, is *importSet, taken map[string]string) error {
	ownerAlias := taken[ep.Pkg.ImportPath]
	fmt.Fprintf(b, "\tvar v %s.%s\n", ownerAlias, ep.BName)
	switch ep.BodyKind {
	case "json":
		beUsed := len(requiredFields(ep.BSet)) > 0
		fmt.Fprintf(b, "\tbe := &hinge.BindError{}\n\tadd := be.AddField\n")
		if !beUsed {
			b.WriteString("\t_ = add\n")
		}
		b.WriteString("\tdata, err := r.Body()\n\tif err != nil {\n\t\treturn v, err\n\t}\n")
		b.WriteString("\tif len(data) > 0 {\n")
		b.WriteString("\t\tif err := hinge.DecodeJSON(data, &v); err != nil {\n")
		b.WriteString("\t\t\tif be2 := hinge.AsBindError(err); be2 != nil {\n\t\t\t\treturn v, be2\n\t\t\t}\n\t\t\treturn v, err\n\t\t}\n")
		if ep.InTransformB {
			recv := "v"
			if ep.InTransformBPtr {
				recv = "(&v)"
			}
			fmt.Fprintf(b, "\t\tif err := %s.InTransform(ctx); err != nil {\n\t\t\treturn v, err\n\t\t}\n", recv)
		}
		b.WriteString("\t}\n")
		emitRequiredChecks(b, ep.BSet)
		b.WriteString("\tif len(be.Fields) > 0 {\n\t\treturn v, be\n\t}\n")
		emitValidate(b, ep.ValidateB, ep.ValidateBPtr)
		b.WriteString("\tif len(be.Fields) > 0 {\n\t\treturn v, be\n\t}\n\treturn v, nil\n")
	case "multipart":
		fmt.Fprintf(b, "\tbe := &hinge.BindError{}\n\tadd := be.AddField\n")
		if len(requiredFields(ep.BSet)) == 0 {
			b.WriteString("\t_ = add\n")
		}
	b.WriteString("\tfm, err := r.MultipartForm()\n\tif err != nil {\n\t\treturn v, err\n\t}\n")
	for _, a := range ep.BSet.Allocs {
		rd2 := &renderer{pkg: ep.Pkg, ownerAlias: ownerAlias, src: a.SrcFile, is: is}
		t, err := rd2.expr(ast.NewIdent(a.TypeName))
		if err != nil {
			return err
		}
			fmt.Fprintf(b, "\tif %s == nil {\n\t\t%s = new(%s)\n\t}\n", a.Access, a.Access, t)
		}
		for _, f := range ep.BSet.Fields {
			switch f.Class {
			case classFile:
				fmt.Fprintf(b, "\tif fhs, ok := fm.File[%q]; ok && len(fhs) > 0 {\n\t\t%s = fhs[0]\n\t}\n", f.Source, f.Access)
			case classFileSlice:
				fmt.Fprintf(b, "\tif fhs, ok := fm.File[%q]; ok {\n\t\t%s = fhs\n\t}\n", f.Source, f.Access)
			default:
				// value part：form 标签字段（语义同 query；错误立即返回，对齐 v0.1 BindMultipart）
				if f.In != "form" {
					continue
				}
				if err := emitMultipartValueBlock(b, f, ep.Pkg, ownerAlias, is); err != nil {
					return err
				}
			}
		}
		if ep.InTransformB {
			recv := "v"
			if ep.InTransformBPtr {
				recv = "(&v)"
			}
			fmt.Fprintf(b, "\tif err := %s.InTransform(ctx); err != nil {\n\t\treturn v, err\n\t}\n", recv)
		}
		emitRequiredChecks(b, ep.BSet)
		b.WriteString("\tif len(be.Fields) > 0 {\n\t\treturn v, be\n\t}\n")
		emitValidate(b, ep.ValidateB, ep.ValidateBPtr)
		b.WriteString("\treturn v, nil\n")
	default:
		return fmt.Errorf("未知 body kind %q", ep.BodyKind)
	}
	return nil
}

// emitMultipartValueBlock multipart value part（错误立即返回，对齐 v0.1）。
func emitMultipartValueBlock(b *strings.Builder, f Field, pkg *Package, ownerAlias string, is *importSet) error {
	rd := &renderer{pkg: pkg, ownerAlias: ownerAlias, src: f.SrcFile, is: is}
	t, err := rd.expr(f.TypeExpr)
	if err != nil {
		return fmt.Errorf("字段 %s: %w", f.GoName, err)
	}
	fmt.Fprintf(b, "\tif vals, ok := fm.Value[%q]; ok && len(vals) > 0 && vals[0] != \"\" {\n", f.Source)
	switch f.Class {
	case classScalar, classPtrScalar:
		fmt.Fprintf(b, "\t\tx, err := hinge.Parse[%s](vals[0], %q)\n", t, f.Source)
	case classSlice:
		fmt.Fprintf(b, "\t\txs, err := hinge.ParseSlice[%s](hinge.Flat(vals), %q)\n", t, f.Source)
	default:
		return fmt.Errorf("multipart 字段 %s 类型不支持", f.GoName)
	}
	b.WriteString("\t\tif err != nil {\n\t\t\treturn v, err\n\t\t}\n")
	switch f.Class {
	case classScalar:
		b.WriteString("\t\t" + f.Access + " = x\n")
	case classPtrScalar:
		b.WriteString("\t\t" + f.Access + " = &x\n")
	case classSlice:
		b.WriteString("\t\t" + f.Access + " = xs\n")
	}
	b.WriteString("\t}\n")
	if f.Def != "" {
		fmt.Fprintf(b, "\tif %s {\n", zeroCmp(f))
		switch f.Class {
		case classSlice:
			fmt.Fprintf(b, "\t\txs, err := hinge.ParseSlice[%s](%s, %q)\n", t, sliceDefSrc(f), f.Source)
		default:
			fmt.Fprintf(b, "\t\tx, err := hinge.Parse[%s](%s, %q)\n", t, strconv.Quote(f.Def), f.Source)
		}
		b.WriteString("\t\tif err != nil {\n\t\t\treturn v, err\n\t\t}\n")
		switch f.Class {
		case classScalar:
			b.WriteString("\t\t" + f.Access + " = x\n")
		case classPtrScalar:
			b.WriteString("\t\t" + f.Access + " = &x\n")
		case classSlice:
			b.WriteString("\t\t" + f.Access + " = xs\n")
		}
		b.WriteString("\t}\n")
	}
	return nil
}

func requiredFields(fs *fieldSet) []Field {
	var out []Field
	for _, f := range fs.Fields {
		if f.Required {
			out = append(out, f)
		}
	}
	return out
}

var ginPathRe = regexp.MustCompile(`\{([^}/]+)\}`)

// frameworkPath 目标框架路由路径（{id} → :id；http 保持 OpenAPI 风格）。
func frameworkPath(target, p string) string {
	if target == "http" {
		return p
	}
	return ginPathRe.ReplaceAllString(p, ":$1")
}

// emitRegister 各框架注册函数 + RegisterAll 聚合器。
func emitRegister(cfg Config, eps []*EndpointIR, target string) (string, error) {
	var adapterPkg, libPkg, routerType string
	switch target {
	case "gin":
		adapterPkg, libPkg, routerType = "servergin", "github.com/gin-gonic/gin", "gin.IRouter"
	case "echo":
		adapterPkg, libPkg, routerType = "serverecho", "github.com/labstack/echo/v4", "echo.Router"
	case "http":
		adapterPkg, libPkg, routerType = "serverhttp", "net/http", "*http.ServeMux"
	}
	is := newImportSet()
	is.add("context", "")
	is.add(hingeImportPath, "")
	adapterPath := hingeImportPath[:strings.LastIndex(hingeImportPath, "/")] + "/" + adapterPkg
	is.add(adapterPath, "")
	if libPkg != "" {
		is.add(libPkg, "")
	}
	taken := map[string]string{}
	owners := map[string][]*EndpointIR{}
	var ownerOrder []string
	for _, ep := range eps {
		if _, ok := owners[ep.Owner]; !ok {
			ownerOrder = append(ownerOrder, ep.Owner)
		}
		owners[ep.Owner] = append(owners[ep.Owner], ep)
		pkgAlias(is, taken, ep.Pkg.ImportPath, ep.Pkg.Name)
	}
	sort.Strings(ownerOrder)

	title := map[string]string{"gin": "Gin", "echo": "Echo", "http": "HTTP"}[target]
	var b strings.Builder
	b.WriteString(genHeader(cfg))
	b.WriteString("package " + cfg.Pkg + "\n\n")
	b.WriteString(is.block())
	b.WriteString("\n")

	verbOf := func(method string) string {
		switch method {
		case "GET", "POST", "PUT", "PATCH", "DELETE", "HEAD", "OPTIONS":
			return method
		}
		return "Any"
	}

	for _, owner := range ownerOrder {
		list := owners[owner]
		ep0 := list[0]
		fmt.Fprintf(&b, "// Register%s%s 把 %s 的全部端点挂到 %s。\n", owner, title, owner, target)
		fmt.Fprintf(&b, "func Register%s%s(r %s, k *hinge.Kernel, ep %s.%s) {\n", owner, title, routerType, taken[ep0.Pkg.ImportPath], owner)
		for _, ep := range list {
			args := ep.qBinder
			if args == "" {
				args = "nil"
			}
			if ep.HasB {
				if args != "" {
					args += ", "
				}
				args += ep.bBinder
			} else if args != "" {
				args += ", nil"
			} else {
				args = "nil, nil"
			}
			closure := emitClosure(ep, taken)
			call := fmt.Sprintf("%s.Handle(k, spec%s%s, %s, %s)", adapterPkg, ep.Owner, ep.Handler, args, closure)
			switch target {
			case "http":
				fmt.Fprintf(&b, "\tr.HandleFunc(%q, %s)\n", ep.Method+" "+ep.FullPath, call)
			case "echo":
				// echo.Router 接口只有 Add（无 verb 方法）
				fmt.Fprintf(&b, "\tr.Add(%q, %q, %s)\n", ep.Method, frameworkPath(target, ep.FullPath), call)
			default:
				fmt.Fprintf(&b, "\tr.%s(%q, %s)\n", verbOf(ep.Method), frameworkPath(target, ep.FullPath), call)
			}
		}
		b.WriteString("}\n\n")
	}
	return b.String(), nil
}

// emitAll All 聚合器（单一文件，避免跨 target 重复声明）。
func emitAll(cfg Config, eps []*EndpointIR) (string, error) {
	is := newImportSet()
	is.add(hingeImportPath, "")
	taken := map[string]string{}
	owners := map[string][]*EndpointIR{}
	var ownerOrder []string
	for _, ep := range eps {
		if _, ok := owners[ep.Owner]; !ok {
			ownerOrder = append(ownerOrder, ep.Owner)
		}
		owners[ep.Owner] = append(owners[ep.Owner], ep)
		pkgAlias(is, taken, ep.Pkg.ImportPath, ep.Pkg.Name)
	}
	sort.Strings(ownerOrder)
	type fw struct {
		adapter, title, routerType, lib string
	}
	var fws []fw
	for _, target := range cfg.Targets {
		switch target {
		case "gin":
			fws = append(fws, fw{"servergin", "Gin", "gin.IRouter", "github.com/gin-gonic/gin"})
		case "echo":
			fws = append(fws, fw{"serverecho", "Echo", "echo.Router", "github.com/labstack/echo/v4"})
		case "http":
			fws = append(fws, fw{"serverhttp", "HTTP", "*http.ServeMux", "net/http"})
		}
	}
	for _, f := range fws {
		is.add(f.lib, "")
	}
	var b strings.Builder
	b.WriteString(genHeader(cfg))
	b.WriteString("package " + cfg.Pkg + "\n\n")
	b.WriteString(is.block())
	b.WriteString("\n")
	b.WriteString("// All 聚合全部 Enterpoint 实例（字段名 = 结构体名）。\n")
	b.WriteString("type All struct {\n")
	for _, owner := range ownerOrder {
		ep0 := owners[owner][0]
		fmt.Fprintf(&b, "\t%s %s.%s\n", owner, taken[ep0.Pkg.ImportPath], owner)
	}
	b.WriteString("}\n\n")
	for _, f := range fws {
		fmt.Fprintf(&b, "// RegisterAll%s 一次装配全部端点（%s）。\n", f.title, f.adapter)
		fmt.Fprintf(&b, "func RegisterAll%s(r %s, k *hinge.Kernel, all All) {\n", f.title, f.routerType)
		for _, owner := range ownerOrder {
			fmt.Fprintf(&b, "\tRegister%s%s(r, k, all.%s)\n", owner, f.title, owner)
		}
		b.WriteString("}\n\n")
	}
	return b.String(), nil
}

// emitClosure 端点方法适配闭包：强类型断言直调（请求期零反射）。
func emitClosure(ep *EndpointIR, taken map[string]string) string {
	ownerAlias := taken[ep.Pkg.ImportPath]
	call := func(qExpr, bExpr string) string {
		if ep.TwoArg {
			return fmt.Sprintf("return ep.%s(ctx, %s)", ep.Handler, qExpr)
		}
		return fmt.Sprintf("return ep.%s(ctx, %s, %s)", ep.Handler, qExpr, bExpr)
	}
	qAny := ""
	if ep.HasQ {
		qAny = "q.(" + ownerAlias + "." + ep.QName + ")"
	} else if !ep.TwoArg {
		qAny = "q" // Q 占位（any），直接透传
	}
	if ep.TwoArg {
		if qAny == "" {
			qAny = "q"
		}
		return "func(ctx context.Context, q, b any) (any, error) {\n\t\t\t" + call(qAny, "") + "\n\t\t}"
	}
	bAny := "b"
	if ep.HasB {
		if ep.BodyKind == "raw" {
			bAny = "b.(hinge.RawBody)"
		} else {
			bAny = "b.(" + ownerAlias + "." + ep.BName + ")"
		}
	}
	if qAny == "" {
		qAny = "q"
	}
	return "func(ctx context.Context, q, b any) (any, error) {\n\t\t\t" + call(qAny, bAny) + "\n\t\t}"
}

// emitTable Enterpoint 守卫 + Endpoints() 对应关系表（业务包内，本地类型免限定）。
func emitTable(pkg *Package, eps []*EndpointIR) (string, error) {
	is := newImportSet()
	is.add(hingeImportPath, "")
	var body strings.Builder

	owners := map[string]bool{}
	var ownerOrder []string
	for _, ep := range eps {
		if !owners[ep.Owner] {
			owners[ep.Owner] = true
			ownerOrder = append(ownerOrder, ep.Owner)
		}
	}
	sort.Strings(ownerOrder)
	for _, owner := range ownerOrder {
		fmt.Fprintf(&body, "var _ hinge.Enterpoint = %s{}\n\n", owner)
		fmt.Fprintf(&body, "// Enterpoint 标记实现（hinge gen 生成）。\nfunc (%s) Enterpoint() {}\n\n", owner)
		fmt.Fprintf(&body, "// Endpoints 路径↔函数对应关系表（openapi 文档与一致性测试的消费源）。\nfunc (%s) Endpoints() []hinge.Endpoint {\n\treturn []hinge.Endpoint{\n", owner)
		for _, ep := range eps {
			if ep.Owner != owner {
				continue
			}
			rd := &renderer{pkg: ep.Pkg, table: true, src: ep.RSrcFile, is: is}
			rExpr, err := rd.expr(ep.RExpr)
			if err != nil {
				return "", fmt.Errorf("%s.%s R 类型: %w", ep.Owner, ep.Handler, err)
			}
			body.WriteString("\t\t{\n")
			fmt.Fprintf(&body, "\t\t\tOwner:   %q,\n", ep.Owner)
			fmt.Fprintf(&body, "\t\t\tHandler: %q,\n", ep.Handler)
			fmt.Fprintf(&body, "\t\t\tMethod:  %q,\n", ep.Method)
			fmt.Fprintf(&body, "\t\t\tPath:    %q,\n", ep.FullPath)
			fmt.Fprintf(&body, "\t\t\tSummary: %q,\n", ep.Summary)
			if ep.Description != "" {
				fmt.Fprintf(&body, "\t\t\tDescription: %q,\n", ep.Description)
			}
			if len(ep.Tags) > 0 {
				fmt.Fprintf(&body, "\t\t\tTags: []string{%s},\n", quoteList(ep.Tags))
			}
			if ep.Status != 0 {
				fmt.Fprintf(&body, "\t\t\tStatus: %d,\n", ep.Status)
			}
			if ep.Deprecated {
				body.WriteString("\t\t\tDeprecated: true,\n")
			}
			if ep.Envelope != "" {
				fmt.Fprintf(&body, "\t\t\tEnvelope: %q,\n", ep.Envelope)
			}
			if ep.Auth != "" {
				fmt.Fprintf(&body, "\t\t\tAuth: %q,\n", ep.Auth)
			}
			if ep.Limit != "" {
				fmt.Fprintf(&body, "\t\t\tLimit: %q,\n", ep.Limit)
			}
			if ep.TimeoutStr != "" {
				fmt.Fprintf(&body, "\t\t\tTimeout: hinge.MustDuration(%q),\n", ep.TimeoutStr)
			}
			if len(ep.Middleware) > 0 {
				fmt.Fprintf(&body, "\t\t\tMiddleware: []string{%s},\n", quoteList(ep.Middleware))
			}
			if ep.HasQ {
				fmt.Fprintf(&body, "\t\t\tQType: hinge.Type[%s](),\n", ep.QName)
			}
			if ep.HasB {
				bType := ep.BName
				if ep.BodyKind == "raw" {
					bType = "hinge.RawBody"
				}
				fmt.Fprintf(&body, "\t\t\tBType: hinge.Type[%s](),\n", bType)
			}
			fmt.Fprintf(&body, "\t\t\tRType: hinge.Type[%s](),\n", rExpr)
			body.WriteString("\t\t},\n")
		}
		body.WriteString("\t}\n}\n\n")
	}

	var b strings.Builder
	b.WriteString("// Code generated by hinge gen. DO NOT EDIT.\n")
	b.WriteString("// Enterpoint 守卫与端点表：路径↔函数对应关系的唯一检视入口。\n\n")
	b.WriteString("package " + pkg.Name + "\n\n")
	b.WriteString(is.block())
	b.WriteString("\n")
	b.WriteString(body.String())
	return b.String(), nil
}

// sliceDefSrc 切片 default 值的源表达式：string 元素不拆逗号（v0.1 SetSliceValue 首分支），其余按逗号展开。
func sliceDefSrc(f Field) string {
	if f.BaseKind == "string" {
		return "[]string{" + strconv.Quote(f.Def) + "}"
	}
	return "hinge.Flat([]string{" + strconv.Quote(f.Def) + "})"
}

func quoteList(vals []string) string {
	parts := make([]string, 0, len(vals))
	for _, v := range vals {
		parts = append(parts, strconv.Quote(v))
	}
	return strings.Join(parts, ", ")
}
